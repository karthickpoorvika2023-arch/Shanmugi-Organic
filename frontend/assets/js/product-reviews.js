/* SHANMUGA V8 — real, approved customer product reviews.
 * Self-contained: no changes to cart, product listing, login or admin JavaScript.
 * Uses Supabase anon client with RLS (never a service-role key). */
(function () {
  'use strict';
  if (!document.body || document.body.dataset.page !== 'product') return;

  var host = document.querySelector('[data-pdp]');
  if (!host) return;
  var slug = new URLSearchParams(window.location.search).get('p');
  var active = new WeakSet();
  var productId = null;
  var client = null;

  function htmlEscape(str) {
    return String(str == null ? '' : str).replace(/[&<>"']/g, function (char) {
      return {'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char];
    });
  }
  function stars(count) {
    var n = Math.max(0, Math.min(5, Math.round(Number(count) || 0)));
    return '★'.repeat(n) + '☆'.repeat(5 - n);
  }
  function announce(box, msg, type) {
    box.textContent = msg;
    box.dataset.state = type || '';
    box.hidden = !msg;
  }
  async function supabaseClient() {
    if (typeof window.__soEnsureSupabase !== 'function') throw new Error('Supabase unavailable.');
    await window.__soEnsureSupabase();
    var api = window.SupabaseClient;
    if (!api || !api.from || !api.auth) throw new Error('Supabase client has not initialized.');
    return api;
  }
  function layout(panel) {
    // Remove previous mock reviewPool content rather than labelling demo reviews as verified customers.
    panel.innerHTML =
      '<section class="so-reviews" aria-label="Customer product reviews">' +
      '<div class="so-reviews__summary" data-so-summary><b class="so-reviews__average">—</b>' +
      '<span class="so-reviews__stars" aria-label="Customer ratings">☆☆☆☆☆</span>' +
      '<span class="so-reviews__count">Loading approved customer reviews…</span></div>' +
      '<div class="so-reviews__grid">' +
      '<div><h3 class="so-reviews__heading">Customer Reviews <span lang="ta">· வாடிக்கையாளர் மதிப்புரைகள்</span></h3>' +
      '<p class="so-reviews__small">Only approved reviews submitted by customers are displayed here.</p>' +
      '<div data-so-review-list role="list"><p class="so-reviews__empty">Loading…</p></div></div>' +
      '<div class="so-reviews__formbox">' +
      '<h3 class="so-reviews__heading">Write a Review <span lang="ta">· மதிப்புரை எழுதுங்கள்</span></h3>' +
      '<p class="so-reviews__small">Choose 1–5 stars and share your experience. Your review appears after approval.</p>' +
      '<form data-so-review-form novalidate>' +
      '<label class="so-reviews__label" id="so-r-label">Your rating *</label>' +
      '<div class="so-reviews__starbuttons" role="group" aria-labelledby="so-r-label">' +
      [1,2,3,4,5].map(function (n) {
        return '<button class="so-reviews__starbtn" type="button" data-so-star="'+n+'" aria-label="'+n+' star'+(n>1?'s':'')+'" aria-pressed="false">★</button>';
      }).join('') + '</div>' +
      '<div class="so-reviews__field"><label class="so-reviews__label" for="so-rev-title">Review title *</label>' +
      '<input id="so-rev-title" name="title" maxlength="100" required placeholder="E.g. Excellent quality"></div>' +
      '<div class="so-reviews__field"><label class="so-reviews__label" for="so-rev-comment">Your review *</label>' +
      '<textarea id="so-rev-comment" name="comment" required minlength="10" maxlength="1500" placeholder="Write about your experience…"></textarea></div>' +
      '<p data-so-auth class="so-reviews__small" aria-live="polite">Checking login…</p>' +
      '<button data-so-submit class="so-reviews__submit" disabled>Submit Review · மதிப்புரை சமர்ப்பிக்க</button>' +
      '<p data-so-message class="so-reviews__message" role="status" aria-live="polite" hidden></p>' +
      '</form></div></div></section>';
  }

  function showResults(panel, product, rows) {
    var list = panel.querySelector('[data-so-review-list]');
    var summary = panel.querySelector('[data-so-summary]');
    if (!list || !summary) return;
    // Count and average are generated by the database's review-approval trigger.
    // The displayed subset is the 30 most recent approved reviews.
    var count = Math.max(0, Number(product.reviews_count || 0));
    var avg = count ? Number(product.rating || 0) : 0;
    summary.querySelector('.so-reviews__average').textContent = count ? avg.toFixed(1) : '—';
    summary.querySelector('.so-reviews__stars').textContent = count ? stars(avg) : '☆☆☆☆☆';
    summary.querySelector('.so-reviews__count').textContent = count + ' approved customer review' + (count === 1 ? '' : 's');
    var tab = host.querySelector('[data-tab="r"]');
    if (tab) tab.textContent = 'Reviews (' + count + ')';
    // Update summary alongside the product price after confirmed public DB read.
    var meta = host.querySelector('.pdp__meta');
    if (meta && meta.children.length >= 2) {
      if (window.App && typeof window.App.stars === 'function') {
        meta.children[0].outerHTML = window.App.stars(avg, 'stars--lg');
      }
      meta.children[1].textContent = (count ? avg.toFixed(1) : '—') + ' · ' + count + ' reviews';
    }
    if (!rows.length) {
      list.innerHTML = '<p class="so-reviews__empty">No approved reviews yet. Be the first to share your experience.</p>';
      return;
    }
    list.innerHTML = rows.map(function (r) {
      var safeDate = r.created_at ? new Date(r.created_at) : null;
      var date = safeDate && !isNaN(safeDate.getTime()) ? safeDate.toLocaleDateString('en-IN') : '';
      return '<article class="so-reviews__item" role="listitem"><div class="so-reviews__itemhead">' +
        '<b>' + htmlEscape(r.reviewer_name || 'Customer') + '</b><time>' + htmlEscape(date) + '</time></div>' +
        '<span class="so-reviews__stars" aria-label="'+ Number(r.rating) +' out of five stars">'+stars(r.rating)+'</span>' +
        (r.title ? '<h4>'+htmlEscape(r.title)+'</h4>' : '') +
        '<p>'+htmlEscape(r.comment || '')+'</p></article>';
    }).join('');
  }

  async function refreshReviews(panel, api, product) {
    var query = await api.from('reviews')
      .select('id,rating,title,comment,reviewer_name,created_at')
      .eq('product_id', product.id).eq('approved', true)
      .order('created_at', {ascending:false}).limit(30);
    if (query.error) throw query.error;
    // Refresh the aggregate in products, which only changes after approval.
    var refreshed = await api.from('products').select('id,rating,reviews_count').eq('id', product.id).single();
    if (refreshed.error) throw refreshed.error;
    showResults(panel, refreshed.data, query.data || []);
  }

  function bindForm(panel, api, product, user) {
    var form = panel.querySelector('[data-so-review-form]');
    if (!form) return;
    var auth = form.querySelector('[data-so-auth]');
    var submit = form.querySelector('[data-so-submit]');
    var message = form.querySelector('[data-so-message]');
    var chosen = 0;
    if (!user) {
      auth.innerHTML = 'Please <a href="signin.html" class="linkish">Sign In</a> to submit a rating. உள்நுழைந்து மதிப்புரை அளிக்கவும்.';
      submit.disabled = true;
      return;
    }
    auth.textContent = 'Signed in. Your review will be visible after approval.';
    submit.disabled = false;
    form.querySelectorAll('[data-so-star]').forEach(function (btn) {
      btn.addEventListener('click', function () {
        chosen = Number(btn.dataset.soStar);
        form.querySelectorAll('[data-so-star]').forEach(function (b) {
          var on = Number(b.dataset.soStar) <= chosen;
          b.classList.toggle('is-selected', on);
          b.setAttribute('aria-pressed', on ? 'true' : 'false');
        });
      });
    });
    form.addEventListener('submit', async function (e) {
      e.preventDefault();
      var title = form.elements.title.value.trim();
      var comment = form.elements.comment.value.trim();
      if (chosen < 1 || chosen > 5) { announce(message, 'Please select a star rating.', 'error'); return; }
      if (!title || title.length > 100 || comment.length < 10 || comment.length > 1500) {
        announce(message, 'Enter a title and a review of at least 10 characters.', 'error'); return;
      }
      submit.disabled = true;
      announce(message, 'Submitting your review…', '');
      try {
        var current = await api.auth.getUser();
        if (current.error || !current.data || !current.data.user) throw new Error('Sign in again to submit a review.');
        var realUser = current.data.user;
        var name = (realUser.user_metadata && (realUser.user_metadata.full_name || realUser.user_metadata.name)) || 'Customer';
        name = String(name).trim().slice(0, 80) || 'Customer';
        var created = await api.from('reviews').insert({
          product_id: product.id, user_id: realUser.id,
          rating: chosen, title: title, comment: comment,
          reviewer_name: name, approved: false
        });
        if (created.error) throw created.error;
        form.reset(); chosen = 0;
        form.querySelectorAll('[data-so-star]').forEach(function (b) {
          b.classList.remove('is-selected'); b.setAttribute('aria-pressed', 'false');
        });
        announce(message, 'Thank you! Your review was submitted and is waiting for approval. நன்றி! உங்கள் மதிப்புரை ஒப்புதலுக்காக அனுப்பப்பட்டது.', 'success');
      } catch (err) {
        console.error('[Customer Reviews] Submit failed', err);
        announce(message, 'Could not submit review. ' + (err.message || 'Please try again.'), 'error');
      } finally { submit.disabled = false; }
    });
  }

  async function initialize(panel) {
    layout(panel);
    var summary = panel.querySelector('.so-reviews__count');
    try {
      if (!slug) throw new Error('Product is not selected.');
      client = await supabaseClient();
      var response = await client.from('products')
        .select('id,rating,reviews_count').eq('slug',slug).maybeSingle();
      if (response.error) throw response.error;
      if (!response.data) throw new Error('This product is not yet available in the live catalogue.');
      var product = response.data;
      productId = product.id;
      await refreshReviews(panel, client, product);
      var authResponse = await client.auth.getUser();
      var user = authResponse.data && authResponse.data.user || null;
      bindForm(panel, client, product, user);
    } catch (error) {
      console.warn('[Customer Reviews] Service not available:', error);
      if (summary) summary.textContent = 'Customer reviews unavailable right now.';
      var list = panel.querySelector('[data-so-review-list]');
      if (list) list.innerHTML = '<p class="so-reviews__empty">Reviews could not be loaded. Please refresh later.</p>';
      var authEl = panel.querySelector('[data-so-auth]');
      if (authEl) authEl.textContent = 'Review submission is not available right now.';
    }
  }

  function attachIfPresent() {
    var panel = host.querySelector('[data-panel="r"]');
    if (!panel || active.has(panel)) return;
    active.add(panel);
    initialize(panel);
  }
  var observer = new MutationObserver(attachIfPresent);
  observer.observe(host, {childList:true,subtree:true});
  attachIfPresent();
})();
