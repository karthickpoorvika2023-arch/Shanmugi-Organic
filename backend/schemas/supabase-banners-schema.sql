-- Create banners table
CREATE TABLE IF NOT EXISTS public.banners (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug            TEXT UNIQUE NOT NULL,           -- banner identifier (B01, B02, etc.)
    title           TEXT NOT NULL,                  -- banner title displayed on frontend
    link            TEXT,                           -- URL link (e.g. products.html?cat=oils)
    image           TEXT NOT NULL,                  -- image URL or base64 data URI
    position        TEXT NOT NULL DEFAULT 'hero',   -- hero | promo | sidebar
    "order"         INTEGER NOT NULL DEFAULT 1,     -- display order (1-20)
    active          BOOLEAN NOT NULL DEFAULT true,  -- active/paused toggle
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Auto-update updated_at timestamp
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER banners_updated_at
    BEFORE UPDATE ON public.banners
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

-- ── Row Level Security (RLS) ────────────────────────────────────────────────

-- Enable RLS
ALTER TABLE public.banners ENABLE ROW LEVEL SECURITY;

-- Public can view active banners (for storefront hero slider)
CREATE POLICY "banners_select_active" ON public.banners
    FOR SELECT
    USING (active = true);

-- Authenticated admins can manage all banners
CREATE POLICY "banners_insert_auth" ON public.banners
    FOR INSERT
    WITH CHECK (auth.role() = 'authenticated');

CREATE POLICY "banners_update_auth" ON public.banners
    FOR UPDATE
    USING (auth.role() = 'authenticated');

CREATE POLICY "banners_delete_auth" ON public.banners
    FOR DELETE
    USING (auth.role() = 'authenticated');

-- ── Indexes ──────────────────────────────────────────────────────────────────

CREATE INDEX IF NOT EXISTS idx_banners_position_order ON public.banners (position, "order");
CREATE INDEX IF NOT EXISTS idx_banners_active ON public.banners (active);
CREATE INDEX IF NOT EXISTS idx_banners_slug ON public.banners (slug);

